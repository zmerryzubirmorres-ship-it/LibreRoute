"""Generate Android branding matching the Windows LibreRoute L mark. Requires Pillow."""
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "app/src/main/res"
GREEN = "#126C58"
DARK = "#103F34"
# Same two rounded bars as LibreRoute-Windows/scripts/make-icon.py, in 256 units.
MARK = "M71,52 H95 Q103,52 103,60 V158 H192 Q200,158 200,166 V192 Q200,200 192,200 H71 Q63,200 63,192 V60 Q63,52 71,52 Z"


def vector(name, color="#FFFFFF", notification=False):
    # Keep adaptive foreground inside Android's safe zone; fill notification area.
    size = 24 if notification else 108
    scale, offset = (0.57, -18) if notification else (0.31, 13.25)
    (RES / "drawable" / name).write_text(f'''<!-- Generated by art/generate_brand_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp" android:height="{size}dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <group android:scaleX="{scale}" android:scaleY="{scale}"
        android:translateX="{offset}" android:translateY="{offset}">
        <path android:fillColor="{color}" android:pathData="{MARK}" />
    </group>
</vector>
''', encoding="utf-8")


def raster(size, color="#FFFFFF", background=None, round_icon=False, adaptive=False):
    factor = 4
    image = Image.new("RGBA", (size * factor, size * factor))
    draw = ImageDraw.Draw(image)
    edge = size * factor - 1
    if background:
        if round_icon:
            draw.ellipse((0, 0, edge, edge), fill=background)
        else:
            draw.rounded_rectangle((0, 0, edge, edge), radius=size * factor * 60 / 256, fill=background)
    scale = size * factor * (0.31 / 108 if adaptive else 1 / 256)
    offset = size * factor * 13.25 / 108 if adaptive else 0
    for bounds in [(63, 52, 103, 200), (63, 158, 200, 200)]:
        draw.rounded_rectangle(tuple(v * scale + offset for v in bounds), radius=8 * scale, fill=color)
    return image.resize((size, size), Image.Resampling.LANCZOS)


def main():
    for name in ["ic_launcher_foreground.xml", "ic_launcher_foreground_dark.xml",
                 "ic_launcher_foreground_light.xml", "ic_launcher_monochrome.xml"]:
        vector(name)
    vector("ic_notification.xml", notification=True)
    (RES / "drawable/ic_brand_logo.xml").write_text(f'''<!-- Generated by art/generate_brand_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="44dp" android:height="44dp"
    android:viewportWidth="256" android:viewportHeight="256">
    <path android:fillColor="{GREEN}" android:pathData="M60,0 H196 Q256,0 256,60 V196 Q256,256 196,256 H60 Q0,256 0,196 V60 Q0,0 60,0 Z" />
    <path android:fillColor="#FFFFFF" android:pathData="{MARK}" />
</vector>
''', encoding="utf-8")
    for density, size in [("mdpi", 48), ("hdpi", 72), ("xhdpi", 96),
                          ("xxhdpi", 144), ("xxxhdpi", 192)]:
        folder = RES / f"mipmap-{density}"
        raster(size, background=GREEN).save(folder / "ic_launcher.webp", lossless=True)
        raster(size, background=GREEN, round_icon=True).save(folder / "ic_launcher_round.webp", lossless=True)
        raster(round(size * 108 / 48), adaptive=True).save(folder / "ic_launcher_foreground.webp", lossless=True)
    for theme, background in [("dark", DARK), ("light", GREEN)]:
        raster(1024, background=background).save(RES / f"drawable-nodpi/preview_app_icon_{theme}.png")
    svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">
  <title>LibreRoute</title>
  <rect width="256" height="256" rx="60" fill="{GREEN}"/>
  <path fill="#FFFFFF" d="{MARK}"/>
</svg>
'''
    (ROOT / "art/logo.svg").write_text(svg, encoding="utf-8")
    (ROOT / "LibreRoute.svg").write_text(svg, encoding="utf-8")


if __name__ == "__main__":
    main()
